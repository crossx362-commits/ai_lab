        // "중국" 또는 미등록 시 코드 그대로
        public static string NameOnly(string cc)
        {
            if (cc == null) return "?";
            string name;
            return Names.TryGetValue(cc, out name) ? name : cc;
        }

        // "CN 중국" 형식
        public static string Display(string cc)
        {
            if (cc == null) return "?";
            string name;
            if (Names.TryGetValue(cc, out name)) return cc + " " + name;
            return cc;
        }
